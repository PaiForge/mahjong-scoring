/**
 * 余白の役割定数
 * 余白定数
 *
 * 画面をまたいで繰り返し現れる「意味のある余白」を、役割の名前で集約する
 * モジュール。`TEXT_LINK_CLASSES`（テキストリンク）や `buttonClasses()`
 * （ボタン）と同じ流儀で、値ではなく役割に名前を付ける。
 *
 * ## 育て方
 *
 * - **役割ベースで足す。値ベースの表（`SPACING_MD = "gap-4"` 等）は作らない。**
 *   Tailwind のスケールをもう一段ラップするだけで情報が増えないうえ、
 *   無関係な箇所が同じ定数を共有し始めると「この役割だけ値を変える」が
 *   できなくなり、ばらつき問題が形を変えて再発する。定数の変更範囲が
 *   「その意味を持つ箇所」と正確に一致することがこのモジュールの価値
 * - **2 回目の登場で足す。** まだ 1 箇所にしか現れない余白に先回りで
 *   名前を付けない。使われない語彙は腐る
 * - **構造まで同じならコンポーネントに昇格する。** 余白と構造を丸ごと
 *   固定できる方が強い（`PracticeFooterActions` が gap-3 を構造ごと
 *   固定しているのが好例）。ここに置くのは、使う側のレイアウトが
 *   揃っていない段階の共通化
 * - 各定数には値の根拠（なぜこの値か）を TSDoc で残す
 */

/**
 * 「押せる面 → その下の補助リンク」の余白
 * 補助リンク余白
 *
 * ボタン（押して始める面）の下に、移動するだけのテキストリンクを添える
 * 構造は画面をまたいで繰り返し現れる（結果画面の「練習一覧に戻る」、
 * 登録 CTA の「ログイン」、設定ゲートの「ログイン」、プロフィール編集の
 * 「スキップ」など）。ここが箇所ごとに違う値だと、同じ意味の並びなのに
 * 画面ごとに詰まったり空いたりして見える。
 *
 * 値は 16px（`gap-4`）。押し間違いを防ぐ縦のタップ間隔として
 * `PracticeFooterActions` が定めている 12px（`gap-3`）より一段広く取り、
 * 「ボタンの一部ではない」ことを距離で示す。
 *
 * **必ず gap で当てること。** リンク側に `pt-*` / `mt-*` を足して差を作ると、
 * 親の縦リズム（`space-y-*`）との合算になり、実際の余白がその場所の親に
 * よって変わってしまう。ボタンが複数並ぶ場合は、ボタン群を `gap-3` の
 * 内側コンテナに包み、その外側にこの定数を当てる。
 */
export const SUB_LINK_GAP = "gap-4";
