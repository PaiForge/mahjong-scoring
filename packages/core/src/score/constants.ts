import type { Fu } from "@pai-forge/riichi-mahjong";

/**
 * アプリが扱う符の値（20〜110符）
 * 符リスト
 *
 * 20符（平和ツモ）と25符（七対子）以外は10刻み。出題・点数表・
 * 回答選択肢はすべてこのリストから引く。
 *
 * ライブラリの `Fu` 型は 170符まで持つ（么九牌の暗槓 4つ + 副底 +
 * 連風牌の雀頭 + 単騎 + 門前ロン）が、このリストは一般的な点数表と同じ
 * 110符 で止めている。120符以上になるには槓子が 3つ以上要り、三槓子に
 * 三暗刻か対々和が必ず付いて 4翻以上、つまり符に関係なく満貫以上になる
 * （暗槓 2つまでなら残りを最大に積んでも 108符）。点数表に 110符超の行が
 * 無いのはこのためで、学習上も扱う意味が無い。生成器は答えがこの範囲外に
 * なる手を出題しない（`isFu` で弾く）。
 * 型注釈が `readonly Fu[]` なので並びの欠けは型では検出できず、
 * constants.test.ts が検証する。
 */
export const FU_VALUES: readonly Fu[] = [
  20, 25, 30, 40, 50, 60, 70, 80, 90, 100, 110,
];

/**
 * 七対子の符（ツモ・ロンとも固定）
 * 七対子符
 *
 * 面子手の積み上げ（副底・和了の符・面子・雀頭・待ち）を通らず、常にこの値。
 */
export const CHIITOITSU_FU: Fu = 25;

/**
 * 平和ツモの符
 * 平和ツモ符
 *
 * 副底のまま据え置く（ツモ符を足さない）特例。
 */
export const PINFU_TSUMO_FU: Fu = 20;

/**
 * 平和ロンの符
 * 平和ロン符
 *
 * 副底に門前ロンの加符が乗る（面子・雀頭・待ちの符は平和の条件上 0）。
 */
export const PINFU_RON_FU: Fu = 30;

/**
 * 有効な符の値かどうかを判定する型ガード
 * 符型ガード
 *
 * クエリパラメータ等の外部入力を `Fu` 型に絞り込むときに使う。
 */
export function isFu(value: number): value is Fu {
  return FU_VALUES.some((fu) => fu === value);
}

