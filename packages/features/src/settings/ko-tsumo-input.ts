/**
 * 子のツモの点数の入力方式
 *
 * - `combined` — 「300/500」のような子から / 親からの組を 1 つの select で選ぶ（既定）。
 *   選択肢は実在する組だけ（core の `koTsumoPaymentOptions`）
 * - `split` — 「子から」「親から」を 2 つの select で別々に選ぶ（従来の入力）。
 *   それぞれの select は相手と連動しないので、実在しない組も入力できる
 *
 * 出題も正解判定も変えない「操作の形」の選択なので、ルール設定ではなく
 * 表示設定に置く。トレーニングだけでなく、記録が残るチャレンジと昇級試験にも効く。
 *
 * **入力方式の違いによる難易度差は許容する（明示的な方針）。** combined は
 * 1 タップで送信され、実在する組しか並ばない（満貫以上なら 5 組。split は
 * 5 × 5 = 25 通りを入力できる）。片側の値しか覚えていない人への補助や、
 * 実在しない組の消去にもなる。`challenge/rule-boundary.ts` が固定する
 * 「設定で選択肢の数が変わる差」と同じ種類の差だが、入力方式は
 * `leaderboard_key` に載せず同じ土俵で比べる。学習アプリとして実在する組
 * だけを選ばせることを優先した判断で、split を選んだ人だけが 2 タップ・
 * 広い選択肢で答えることになる。また、この設定を入れる前の記録はすべて
 * split で入力されたもので、以降の combined の記録と難易度の条件が違う。
 *
 * web の設定ページは会員限定（`MembersOnlyGate`）のため、web のゲストは
 * 切り替えられない。端末に保存済みの値があればそれを使い、無ければ既定の
 * combined になる（ログイン中に split を選んでからログアウトした人は split
 * のまま）。既存のゲストが従来の入力へ戻す導線が無いことは許容している。
 * モバイルの設定はゲストも変えられる。
 */
export type KoTsumoInputMode = "combined" | "split";

/** 1 タップで答えられ、実在する組だけが並ぶ combined を既定にする */
export const DEFAULT_KO_TSUMO_INPUT: KoTsumoInputMode = "combined";
